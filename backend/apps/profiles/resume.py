def institute_name(user, lang: str) -> str:
    institution = user.institution
    if lang == "en" and institution.is_default:
        return DEFAULT_INSTITUTE_EN
    return institution.name


@dataclass
class ResumeData:
    lang: str
    name: str
    headline: str
    summary: str
    subtitle: str
    contacts: list[tuple[str, str]] = field(default_factory=list)
    portfolio_url: str = ""
    skills: list[dict] = field(default_factory=list)
    achievements: list[dict] = field(default_factory=list)
    projects: list[dict] = field(default_factory=list)
    badges: list[str] = field(default_factory=list)
    activity: list[tuple[str, str]] = field(default_factory=list)
    brand: str = "Talent Hub"
    logo_path: str | None = None


def get_resume(user) -> Resume:
    resume, _ = Resume.objects.get_or_create(user=user)
    return resume


def _short(text: str, limit: int) -> str:
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def leaderboard_rank(user) -> int:
    User = get_user_model()
    return User.objects.filter(role=User.Role.STUDENT, is_active=True, xp__gt=user.xp).count() + 1


def auto_summary(user, lang: str, skills: list[dict], achievements: list[dict], projects: list[dict]) -> str:
    """AI bo'lmasa ishlatiladigan shablon xulosa. Faqat platformadagi faktlardan tuziladi."""
    top = ", ".join(s["name"] for s in skills[:3])
    faculty = user.faculty.name if user.faculty else ""
    if lang == "en":
        parts = [f"{institute_name(user, 'en')} student" + (f" ({faculty})" if faculty else "") + "."]
        if top:
            parts.append(f"Key skills: {top}.")
        if achievements:
            parts.append(f"{len(achievements)} verified achievement(s), including {achievements[0]['title']}.")
        if projects:
            parts.append(f"Works on {len(projects)} project(s), e.g. {projects[0]['title']}.")
        parts.append("Motivated to grow through real projects and internships.")
    else:
        parts = [(f"{faculty} " if faculty else "") + f"{institute_name(user, 'uz')} talabasi."]
        if top:
            parts.append(f"Asosiy ko'nikmalar: {top}.")
        if achievements:
            parts.append(f"{len(achievements)} ta tasdiqlangan yutuq, jumladan: {achievements[0]['title']}.")
        if projects:
            parts.append(f"{len(projects)} ta loyihada ishtirok etadi, masalan: {projects[0]['title']}.")
        parts.append("Real loyihalar va amaliyot orqali rivojlanishga intiladi.")
    return " ".join(parts)


def collect(user, lang: str = "uz", public: bool = False, portfolio_url: str = "") -> ResumeData:
    """Rezyume uchun ma'lumotlarni yig'adi. `public=True` bo'lsa, ruxsatsiz telefon va email yashiriladi."""
    lang = lang if lang in LANGS else "uz"
    labels = LABELS[lang]
    resume = get_resume(user)
    level = level_for_xp(user.xp)

    skills = [
        {"name": us.skill.name, "level": us.level, "endorsed": bool(us.endorsement_count)}
        for us in UserSkill.objects.filter(user=user)
        .select_related("skill")
        .annotate(endorsement_count=Count("endorsements"))
        .order_by("-level", "skill__name")[:MAX_SKILLS]
    ]
    achievements = [
        {
            "title": a.title,
            "kind": KIND_EN.get(a.kind, a.get_kind_display()) if lang == "en" else a.get_kind_display(),
            "date": a.achieved_on,
            "description": _short(a.description, 220),
        }
        for a in Achievement.objects.filter(user=user, status=Achievement.Status.APPROVED).order_by("-achieved_on")[
            :MAX_ACHIEVEMENTS
        ]
    ]
    projects = [
        {
            "title": m.project.title,
            "stage": STAGE_EN.get(m.project.stage) if lang == "en" else m.project.get_stage_display(),
            "role": m.role,
            "description": _short(m.project.description, 240),
            "link": m.project.demo_url or m.project.repo_url,
        }
        for m in user.project_memberships.filter(status="active").select_related("project")[:MAX_PROJECTS]
    ]
    badges = [ub.badge.name for ub in user.badges.select_related("badge").order_by("-awarded_at")[:MAX_BADGES]]

    headline, summary = resume.text(lang)
    if not summary:
        summary = auto_summary(user, lang, skills, achievements, projects)

    institute = institute_name(user, lang)
    subtitle_parts = [user.faculty.name if user.faculty else institute]
    if user.course:
        subtitle_parts.append(labels["course"].format(n=user.course))
    subtitle_parts.append(institute if user.faculty else labels["student"])

    contacts = []
    show_private = not public or resume.show_contacts_public
    if show_private and user.email:
        contacts.append(("Email", user.email))
    if show_private and resume.phone:
        contacts.append((labels["phone"], resume.phone))
    if user.github_url:
        contacts.append(("GitHub", user.github_url))
    if user.linkedin_url:
        contacts.append(("LinkedIn", user.linkedin_url))

    solved = Submission.objects.filter(user=user, status=Submission.Status.ACCEPTED).count()
    level_name = LEVEL_EN.get(level["number"], level["name"]) if lang == "en" else level["name"]
    activity = [
        (labels["level"], f"{level['number']} · {level_name}"),
        (labels["xp"], f"{user.xp} XP"),
        (labels["rank"], f"#{leaderboard_rank(user)}"),
        (labels["solved"], str(solved)),
    ]

    return ResumeData(
        lang=lang,
        name=user.get_full_name() or user.username,
        headline=headline,
        summary=summary,
        subtitle=" · ".join(subtitle_parts),
        contacts=contacts,
        portfolio_url=portfolio_url if user.is_public else "",
        skills=skills,
        achievements=achievements,
        projects=projects,
        badges=badges,
        activity=activity,
        brand=user.institution.brand_name,
        logo_path=_logo_path(user.institution),
    )


def _logo_path(institution):
    if institution.logo:
        try:
            return institution.logo.path
        except (NotImplementedError, ValueError):
            return None
    return finders.find("web/img/adti-logo-128.png") if institution.is_default else None


