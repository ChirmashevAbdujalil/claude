_fonts_ready = False


def _register_fonts():
    global _fonts_ready
    if _fonts_ready:
        return
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    pdfmetrics.registerFont(TTFont("DejaVu", str(FONT_DIR / "DejaVuSans.ttf")))
    pdfmetrics.registerFont(TTFont("DejaVu-Bold", str(FONT_DIR / "DejaVuSans-Bold.ttf")))
    pdfmetrics.registerFontFamily("DejaVu", normal="DejaVu", bold="DejaVu-Bold")
    _fonts_ready = True


def render_pdf(data: ResumeData) -> bytes:
    """A4 PDF rezyume. Kirill va o'zbekcha belgilar uchun DejaVu shrifti ishlatiladi."""
    from reportlab.graphics.barcode.qr import QrCodeWidget
    from reportlab.graphics.shapes import Drawing
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        HRFlowable,
        Image,
        KeepTogether,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    _register_fonts()
    labels = LABELS[data.lang]
    brand, primary, teal = colors.HexColor("#062d3b"), colors.HexColor("#0e5a73"), colors.HexColor("#168a9c")
    muted, line, gold = colors.HexColor("#5f747c"), colors.HexColor("#dbe4e7"), colors.HexColor("#b45309")

    def style(name, **kw):
        base = {"fontName": "DejaVu", "fontSize": 9.5, "leading": 13.5, "textColor": colors.HexColor("#0b1d24")}
        base.update(kw)
        return ParagraphStyle(name, **base)

    s_name = style("name", fontName="DejaVu-Bold", fontSize=20, leading=24, textColor=colors.white)
    s_head = style("head", fontName="DejaVu-Bold", fontSize=11, leading=15, textColor=colors.HexColor("#9be3ef"))
    s_sub = style("sub", fontSize=8.5, leading=12, textColor=colors.HexColor("#d5e7ec"))
    s_qr = style("qr", fontSize=6.5, leading=8, textColor=colors.HexColor("#d5e7ec"), alignment=1)
    s_h2 = style("h2", fontName="DejaVu-Bold", fontSize=11.5, leading=15, textColor=primary, spaceBefore=10)
    s_body = style("body")
    s_small = style("small", fontSize=8.5, leading=12, textColor=muted)
    s_item = style("item", fontName="DejaVu-Bold", fontSize=10, leading=13.5)
    s_contact = style("contact", fontSize=8.5, leading=12, textColor=muted)

    def p(text, st):
        return Paragraph(text, st)

    def section(title):
        return [
            p(escape(title), s_h2),
            HRFlowable(width="100%", thickness=0.8, color=line, spaceBefore=2, spaceAfter=6),
        ]

    story = []

    # Sarlavha: logo | ism, yo'nalish | QR
    logo_path = data.logo_path
    logo = Image(logo_path, width=16 * mm, height=16 * mm) if logo_path else Spacer(16 * mm, 16 * mm)
    head_lines = [p(escape(data.name), s_name)]
    if data.headline:
        head_lines.append(p(escape(data.headline), s_head))
    head_lines.append(p(escape(data.subtitle), s_sub))
    qr_cell = ""
    if data.portfolio_url:
        widget = QrCodeWidget(data.portfolio_url)
        widget.barFillColor = brand
        x1, y1, x2, y2 = widget.getBounds()
        size = 21 * mm
        drawing = Drawing(size, size, transform=[size / (x2 - x1), 0, 0, size / (y2 - y1), 0, 0])
        drawing.add(widget)
        qr_box = Table([[drawing]], colWidths=[size + 2 * mm], rowHeights=[size + 2 * mm])
        qr_box.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), colors.white),
                    ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ]
            )
        )
        qr_cell = [qr_box, Spacer(1, 1.5 * mm), p(escape(labels["scan"]), s_qr)]
    header = Table([[logo, head_lines, qr_cell]], colWidths=[22 * mm, None, 30 * mm])
    header.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), brand),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 4 * mm),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4 * mm),
                ("TOPPADDING", (0, 0), (-1, -1), 5 * mm),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5 * mm),
                ("LINEBELOW", (0, 0), (-1, -1), 3, teal),
            ]
        )
    )
    story.append(header)

    contacts = [f"<b>{escape(k)}:</b> {escape(v)}" for k, v in data.contacts]
    if data.portfolio_url:
        contacts.append(f"<b>{escape(labels['portfolio'])}:</b> {escape(data.portfolio_url)}")
    if contacts:
        story += [Spacer(1, 3 * mm), p("   ·   ".join(contacts), s_contact)]

    if data.summary:
        story += section(labels["summary"]) + [p(escape(data.summary), s_body)]

    if data.skills:
        story += section(labels["skills"])
        cells = []
        for skill in data.skills:
            on, off = "●" * skill["level"], "●" * (5 - skill["level"])
            dots = f'<font color="#168a9c">{on}</font><font color="#c9d6da">{off}</font>'
            tick = ""
            if skill["endorsed"]:
                note = escape(labels["endorsed"])
                tick = f' <font color="#059669">✓</font> <font size="7.5" color="#5f747c">{note}</font>'
            cells.append(p(f"<b>{escape(skill['name'])}</b>  {dots}{tick}", s_body))
        if len(cells) % 2:
            cells.append("")
        rows = [cells[i : i + 2] for i in range(0, len(cells), 2)]
        table = Table(rows, colWidths=["50%", "50%"])
        table.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
        story.append(table)

    if data.achievements:
        story += section(labels["achievements"])
        for a in data.achievements:
            when = a["date"].strftime("%m.%Y") if isinstance(a["date"], date) else ""
            block = [
                p(
                    f"{escape(a['title'])} <font color='#059669'>✓</font>"
                    f"<font name='DejaVu' size='8.5' color='#5f747c'>  ·  {escape(a['kind'])}  ·  {when}</font>",
                    s_item,
                )
            ]
            if a["description"]:
                block.append(p(escape(a["description"]), s_small))
            block.append(Spacer(1, 2.5 * mm))
            story.append(KeepTogether(block))

    if data.projects:
        story += section(labels["projects"])
        for pr in data.projects:
            meta = f"{labels['role']}: {pr['role']}  ·  {labels['stage']}: {pr['stage']}"
            gray = "<font name='DejaVu' size='8.5' color='#5f747c'>"
            block = [p(f"{escape(pr['title'])}{gray}  ·  {escape(meta)}</font>", s_item)]
            if pr["description"]:
                block.append(p(escape(pr["description"]), s_small))
            if pr["link"]:
                block.append(p(f"<font color='#0e5a73'>{escape(pr['link'])}</font>", s_small))
            block.append(Spacer(1, 2.5 * mm))
            story.append(KeepTogether(block))

    tail = []
    if data.badges:
        tail += section(labels["badges"]) + [p(escape("  ·  ".join(data.badges)), s_body)]
    tail += section(labels["activity"])
    stats = Table(
        [
            [
                p(f"<font size='8' color='#5f747c'>{escape(k)}</font><br/><b>{escape(v)}</b>", s_body)
                for k, v in data.activity
            ]
        ],
        colWidths=["25%"] * 4,
    )
    stats.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f3f6f7")),
                ("BOX", (0, 0), (-1, -1), 0.6, line),
                ("INNERGRID", (0, 0), (-1, -1), 0.6, line),
                ("TOPPADDING", (0, 0), (-1, -1), 2.5 * mm),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5 * mm),
                ("LEFTPADDING", (0, 0), (-1, -1), 3 * mm),
            ]
        )
    )
    tail.append(stats)
    story.append(KeepTogether(tail))

    footer = labels["footer"].format(brand=data.brand, date=timezone.localdate().strftime("%d.%m.%Y"))

    def on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("DejaVu", 7.5)
        canvas.setFillColor(muted)
        canvas.drawString(16 * mm, 10 * mm, footer)
        canvas.drawRightString(A4[0] - 16 * mm, 10 * mm, str(doc.page))
        canvas.setFillColor(gold)
        canvas.rect(0, A4[1] - 2 * mm, A4[0], 2 * mm, stroke=0, fill=1)
        canvas.restoreState()

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=12 * mm,
        bottomMargin=18 * mm,
        title=f"{data.name} · CV",
        author=data.brand,
    )
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()


def qr_svg(value: str, size: int = 68) -> str:
    """Kichik SVG QR kod (sahifada ko'rsatish uchun, tashqi kutubxonasiz)."""
    from reportlab.graphics.barcode.qr import QrCodeWidget

    qr = QrCodeWidget(value).qr
    qr.make()
    quiet, count = 2, qr.getModuleCount()
    cells = "".join(
        f"M{c + quiet},{r + quiet}h1v1h-1z" for r, row in enumerate(qr.modules) for c, dark in enumerate(row) if dark
    )
    box = count + 2 * quiet
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {box} {box}" width="{size}" height="{size}" '
        f'shape-rendering="crispEdges" role="img" aria-label="QR"><rect width="{box}" height="{box}" fill="#fff"/>'
        f'<path d="{cells}" fill="#062d3b"/></svg>'
    )


def filename(user, lang: str) -> str:
    base = "cv" if lang == "en" else "rezyume"
    return f"{base}-{user.username}.pdf"


def portfolio_url(user, request=None) -> str:
    if not user.portfolio_slug or not user.is_public:
        return ""
    path = f"/u/{user.portfolio_slug}/"
    if request is not None:
        return request.build_absolute_uri(path)
    base = user.institution.base_url()
    return base + path if base else ""
